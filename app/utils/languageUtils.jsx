export const getVersions = (language) => {
    let version = LANGUAGE.find(
        (l) => l.language.toLowerCase() === language.toLowerCase()
    );

    if (version) {
        return version.version;
    } else {
        return "";
    }
};

export const getExtension = (language) => {
    let version = LANGUAGE.find(
        (l) => l.language.toLowerCase() === language.toLowerCase()
    );

    if (version) {
        return version.coded_extension;
    } else {
        return "";
    }
};

// Helper function to map language names to supported piston API languages
export const mapLanguageToPiston = (language) => {
    const languageMap = {
        'javascript': 'javascript',
        'js': 'javascript',
        'python': 'python',
        'java': 'java',
        'cpp': 'cpp',
        'c++': 'cpp',
        'c': 'c',
        'php': 'php',
        'go': 'go',
        'rust': 'rust',
        'sql': 'sql',
        'typescript': 'typescript',
        'ts': 'typescript',
        'ruby': 'ruby',
        'rb': 'ruby',
        'swift': 'swift',
        'kotlin': 'kotlin',
        'scala': 'scala',
        'r': 'r',
        'bash': 'bash',
        'powershell': 'powershell',
        'ps1': 'powershell',
    };

    const langLower = language.toLowerCase();

    // Try exact match first
    if (languageMap[langLower]) {
        return languageMap[langLower];
    }

    // Try partial match
    for (const [key, value] of Object.entries(languageMap)) {
        if (langLower.includes(key)) {
            return value;
        }
    }

    // Default to javascript
    return 'javascript';
};



